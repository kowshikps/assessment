CREATE TABLE trades (
  event_id BIGINT PRIMARY KEY,
  event_type VARCHAR(6) NOT NULL,
  trading_account VARCHAR(100) NOT NULL,
  security_id VARCHAR(100) NOT NULL,
  quantity BIGINT NOT NULL CHECK (quantity > 0),
  cancelled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX trades_position ON trades(trading_account, security_id);
CREATE TABLE event_history (
  sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL REFERENCES trades(event_id),
  event_type VARCHAR(6) NOT NULL,
  trading_account VARCHAR(100) NOT NULL,
  security_id VARCHAR(100) NOT NULL,
  quantity BIGINT NOT NULL
);
CREATE INDEX history_position ON event_history(trading_account, security_id);
